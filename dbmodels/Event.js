const mongoose=require("mongoose");
const eventSchema=new mongoose.Schema({
title:{
type:String,
required:true,
trim:true
},
venue:{
type:String,
required:true,
trim:true
},
date:{
type:Date,
required:true
},
price:{
type:Number,
required:true,
min:0
},
seats:{
type:Number,
required:true,
min:0
},
description:{
type:String,
default:""
}
},{timestamps:true});
module.exports=mongoose.model("Event",eventSchema);